import { useState, useEffect } from "react";
import { AlertCircle, Boxes, Loader2, Plus, RotateCcw, Sparkles } from "lucide-react";
import { Button, Dialog, Input, Select } from "@/components/ui";
import { ConfirmActionModal } from "@/components/modals/ConfirmActionModal";
import { ApiError } from "@/lib/api";
import { useCreateProduct, usePrincipals } from "@/features/products/queries";
import type { DivisionValue, PrincipalRow } from "@/features/products/types";

export function AddProductModal({
  open,
  onClose,
  principals: propPrincipals,
  onOpenAddPrincipal,
}: {
  open: boolean;
  onClose: () => void;
  principals?: PrincipalRow[];
  onOpenAddPrincipal?: () => void;
}) {
  const create = useCreateProduct();

  const principalsQuery = usePrincipals({ enabled: open && propPrincipals === undefined });
  const principals =
    propPrincipals && propPrincipals.length > 0
      ? propPrincipals
      : (principalsQuery.data?.items ?? []);

  const [principalId, setPrincipalId] = useState("");
  const [name, setName] = useState("");
  const [sku, setSku] = useState("");
  const [isSkuAutoGenerated, setIsSkuAutoGenerated] = useState(false);
  const [division, setDivision] = useState<DivisionValue>("LUB");
  const [unit, setUnit] = useState("Ltr");
  const [listPrice, setListPrice] = useState<string>("");
  const [errorMessage, setErrorMessage] = useState("");
  const [showDiscardConfirm, setShowDiscardConfirm] = useState(false);

  const selectedPrincipalId = principalId || principals[0]?.id || "";
  const selectedPrincipal = principals.find((p) => p.id === selectedPrincipalId);

  // Auto-generate suggested SKU based on principal code and product name initials
  const handleAutoSuggestSku = () => {
    const prefix = (selectedPrincipal?.name || "PR")
      .replace(/[^A-Z0-9]/gi, "")
      .slice(0, 3)
      .toUpperCase();
    const namePrefix =
      name
        .trim()
        .replace(/[^A-Z0-9]/gi, "")
        .slice(0, 3)
        .toUpperCase() || "SKU";
    const rand = Math.floor(100 + Math.random() * 900);
    setSku(`${prefix}-${namePrefix}-${rand}`);
    setIsSkuAutoGenerated(true);
    if (errorMessage) setErrorMessage("");
  };

  const handleClearSku = () => {
    setSku("");
    setIsSkuAutoGenerated(false);
  };

  // Reset form when modal opens
  useEffect(() => {
    if (open) {
      setName("");
      setSku("");
      setIsSkuAutoGenerated(false);
      setListPrice("");
      setDivision("LUB");
      setUnit("Ltr");
      setErrorMessage("");
      setShowDiscardConfirm(false);
    }
  }, [open]);

  // Set default principalId once principals are loaded and no selection exists
  useEffect(() => {
    if (open && principals.length > 0 && !principalId) {
      setPrincipalId(principals[0].id);
    }
  }, [open, principals, principalId]);

  const resetForm = () => {
    setName("");
    setSku("");
    setIsSkuAutoGenerated(false);
    setListPrice("");
    setDivision("LUB");
    setUnit("Ltr");
    setErrorMessage("");
    setShowDiscardConfirm(false);
  };

  const isDirty = Boolean(
    name.trim() ||
      (sku.trim() && !isSkuAutoGenerated) ||
      listPrice.trim()
  );

  const handleAttemptClose = () => {
    if (create.isPending) return;
    if (isDirty) {
      setShowDiscardConfirm(true);
    } else {
      resetForm();
      onClose();
    }
  };

  const handleForceClose = () => {
    resetForm();
    onClose();
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!name.trim() || !selectedPrincipalId || create.isPending) return;

    const priceNum = listPrice.trim() ? Number(listPrice) : null;
    if (priceNum !== null && (isNaN(priceNum) || priceNum < 0)) {
      setErrorMessage("Please enter a valid non-negative selling price.");
      return;
    }

    try {
      setErrorMessage("");
      await create.mutateAsync({
        name: name.trim(),
        principalId: selectedPrincipalId,
        sku: sku.trim() || null,
        division: division || "LUB",
        unit: unit.trim() || "Ltr",
        basePrice: priceNum,
        active: true,
      });

      resetForm();
      onClose();
    } catch (err) {
      if (err instanceof ApiError) {
        setErrorMessage(err.message);
      } else {
        setErrorMessage("Failed to add product. Please try again.");
      }
    }
  };

  const shortUnit = unit.split(" ")[0] || "unit";

  return (
    <>
      <Dialog
        open={open}
        onClose={handleAttemptClose}
        title={
          <div className="flex items-center gap-2">
            <Boxes className="h-4.5 w-4.5 text-brand shrink-0" />
            <span>Add Catalog Product</span>
          </div>
        }
        description="Register a new catalog SKU under a principal brand with benchmark pricing."
        maxWidth="max-w-xl"
        footer={
          <>
            <Button
              variant="outline"
              size="sm"
              onClick={handleAttemptClose}
              type="button"
              disabled={create.isPending}
            >
              Cancel
            </Button>
            <Button
              size="sm"
              onClick={handleSubmit}
              disabled={!name.trim() || !selectedPrincipalId || create.isPending}
            >
              {create.isPending ? (
                <>
                  <Loader2 className="h-3.5 w-3.5 mr-1.5 animate-spin" />
                  Saving Product…
                </>
              ) : (
                "Add Product"
              )}
            </Button>
          </>
        }
      >
        <form onSubmit={handleSubmit} className="space-y-4 text-xs">
          {errorMessage && (
            <div
              role="alert"
              className="rounded-lg bg-red-soft/80 border border-red/30 p-2.5 text-xs text-red font-medium flex items-center gap-2 animate-in fade-in-50"
            >
              <AlertCircle className="h-4 w-4 shrink-0 text-red" />
              <span>{errorMessage}</span>
            </div>
          )}

          {/* 2-Column Responsive Form Grid */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-x-4 gap-y-3.5">
            {/* 1. Principal Brand Selection */}
            <div>
              <div className="flex items-center justify-between mb-1.5">
                <label
                  htmlFor="add-product-principal"
                  className="text-xs font-semibold text-ink"
                >
                  Principal Brand <span className="text-red font-semibold" aria-hidden="true">*</span>
                </label>
                {onOpenAddPrincipal && (
                  <button
                    type="button"
                    onClick={() => {
                      if (isDirty) {
                        setShowDiscardConfirm(true);
                      } else {
                        onClose();
                        onOpenAddPrincipal();
                      }
                    }}
                    className="text-[11.5px] font-semibold text-brand hover:text-brand-ink inline-flex items-center gap-1 transition-colors cursor-pointer focus-visible:outline-none focus-visible:underline"
                    aria-label="Add new brand"
                  >
                    <Plus className="h-3 w-3" />
                    <span>New Brand</span>
                  </button>
                )}
              </div>
              {principals.length === 0 ? (
                <div className="rounded-lg border border-amber-300 bg-amber-50 p-2 text-xs text-amber-900 font-medium flex items-center justify-between">
                  <span>No brands found.</span>
                  {onOpenAddPrincipal && (
                    <Button
                      size="xs"
                      onClick={() => {
                        onClose();
                        onOpenAddPrincipal();
                      }}
                      type="button"
                    >
                      Add Brand
                    </Button>
                  )}
                </div>
              ) : (
                <Select
                  id="add-product-principal"
                  className="w-full"
                  selectClassName="w-full h-9"
                  value={selectedPrincipalId}
                  onChange={(e) => {
                    setPrincipalId(e.target.value);
                    if (errorMessage) setErrorMessage("");
                  }}
                  disabled={create.isPending}
                >
                  {principals.map((p) => (
                    <option key={p.id} value={p.id}>
                      {p.name} {p.productCount ? `(${p.productCount} products)` : ""}
                    </option>
                  ))}
                </Select>
              )}
            </div>

            {/* 2. Product Name */}
            <div>
              <label
                htmlFor="add-product-name"
                className="text-xs font-semibold text-ink block mb-1.5"
              >
                Product Name <span className="text-red font-semibold" aria-hidden="true">*</span>
              </label>
              <Input
                id="add-product-name"
                required
                placeholder="e.g. Castrol Magnatec 5W-30"
                value={name}
                onChange={(e) => {
                  setName(e.target.value);
                  if (errorMessage) setErrorMessage("");
                }}
                disabled={create.isPending}
                className="h-9"
              />
            </div>

            {/* 3. SKU Field with Integrated Generator */}
            <div>
              <div className="flex items-center justify-between mb-1.5">
                <div className="flex items-center gap-1.5">
                  <label
                    htmlFor="add-product-sku"
                    className="text-xs font-semibold text-ink"
                  >
                    Product SKU / Code
                  </label>
                  <span className="text-[11px] text-muted font-normal">(Optional)</span>
                </div>
                {isSkuAutoGenerated && sku && (
                  <span className="inline-flex items-center px-1.5 py-0.2 rounded text-[10px] font-semibold bg-brand-soft text-brand-ink border border-brand/20">
                    Auto-suggested
                  </span>
                )}
              </div>
              <div className="relative flex items-center">
                <Input
                  id="add-product-sku"
                  placeholder="CAS-MAG-50"
                  value={sku}
                  onChange={(e) => {
                    setSku(e.target.value.toUpperCase());
                    setIsSkuAutoGenerated(false);
                    if (errorMessage) setErrorMessage("");
                  }}
                  className="h-9 pr-24 uppercase font-mono text-xs"
                  disabled={create.isPending}
                />
                <div className="absolute right-1 flex items-center gap-1">
                  {sku && (
                    <button
                      type="button"
                      onClick={handleClearSku}
                      className="px-1.5 py-1 text-[10.5px] font-medium text-muted hover:text-ink cursor-pointer transition-colors"
                      title="Clear SKU"
                    >
                      Clear
                    </button>
                  )}
                  <button
                    type="button"
                    onClick={handleAutoSuggestSku}
                    aria-label={isSkuAutoGenerated ? "Regenerate SKU" : "Auto-suggest SKU"}
                    className="px-2 py-1 text-[11px] font-semibold text-brand bg-brand-soft hover:bg-brand/20 rounded-md border border-brand/25 inline-flex items-center gap-1 cursor-pointer transition-all active:scale-95 focus-visible:outline-none focus-visible:ring-1 focus-visible:ring-brand"
                    title="Generate suggested SKU"
                  >
                    {isSkuAutoGenerated ? (
                      <>
                        <RotateCcw className="h-3 w-3" />
                        <span>Regen</span>
                      </>
                    ) : (
                      <>
                        <Sparkles className="h-3 w-3" />
                        <span>Suggest</span>
                      </>
                    )}
                  </button>
                </div>
              </div>
            </div>

            {/* 4. Default Benchmark Price */}
            <div>
              <div className="flex items-center gap-1.5 mb-1.5">
                <label
                  htmlFor="add-product-price"
                  className="text-xs font-semibold text-ink"
                >
                  Default Benchmark Price
                </label>
                <span className="text-[11px] text-muted font-normal">(Optional)</span>
              </div>
              <div className="relative flex items-center">
                <span className="pointer-events-none absolute left-3 text-xs font-semibold text-muted select-none">
                  ₹
                </span>
                <Input
                  id="add-product-price"
                  type="number"
                  step="0.01"
                  min="0"
                  placeholder="0.00"
                  value={listPrice}
                  onChange={(e) => {
                    setListPrice(e.target.value);
                    if (errorMessage) setErrorMessage("");
                  }}
                  disabled={create.isPending}
                  className="h-9 pl-7 pr-16 tabular-nums text-xs"
                />
                <span className="pointer-events-none absolute right-3 text-[11px] font-semibold text-muted/70 select-none">
                  / {shortUnit}
                </span>
              </div>
            </div>

            {/* 5. Division */}
            <div>
              <label
                htmlFor="add-product-division"
                className="text-xs font-semibold text-ink block mb-1.5"
              >
                Division <span className="text-red font-semibold" aria-hidden="true">*</span>
              </label>
              <Select
                id="add-product-division"
                className="w-full"
                selectClassName="w-full h-9"
                value={division}
                onChange={(e) => setDivision(e.target.value as DivisionValue)}
                disabled={create.isPending}
              >
                <option value="LUB">Lubricants (LUB)</option>
                <option value="WES">Welding &amp; Equip (WES)</option>
              </Select>
            </div>

            {/* 6. Unit of Measure */}
            <div>
              <label
                htmlFor="add-product-unit"
                className="text-xs font-semibold text-ink block mb-1.5"
              >
                Unit of Measure <span className="text-red font-semibold" aria-hidden="true">*</span>
              </label>
              <Select
                id="add-product-unit"
                className="w-full"
                selectClassName="w-full h-9"
                value={unit}
                onChange={(e) => setUnit(e.target.value)}
                disabled={create.isPending}
              >
                <option value="Ltr">Litre (Ltr)</option>
                <option value="Kg">Kilogram (Kg)</option>
                <option value="Pcs">Pieces (Pcs)</option>
                <option value="Drum">Drum (208L)</option>
                <option value="Can">Can (20L)</option>
                <option value="Box">Box / Carton</option>
                <option value="Set">Set / Kit</option>
              </Select>
            </div>
          </div>
        </form>
      </Dialog>

      {/* Discard confirmation modal if user attempts to exit with unsaved form input */}
      <ConfirmActionModal
        open={showDiscardConfirm}
        onClose={() => setShowDiscardConfirm(false)}
        onConfirm={handleForceClose}
        title="Discard unsaved product?"
        body="You have entered product details. Closing now will discard all unsaved changes."
        confirmLabel="Discard Changes"
        destructive
      />
    </>
  );
}
